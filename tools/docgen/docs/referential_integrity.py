# -*- coding: utf-8 -*-
from docbuild import *

TOPIC = "Referentional integrity"
CATEGORY = "Database Design Principles"
TITLE = "Referensial Butunlik"
SUBTITLE = "Tashqi kalitlar va bog'lanishlarning ishonchliligi"
FILENAME = "Referentional integrity.docx"


def build(d):
    h1(d, "1. Tamoyilning mohiyati")

    para(d, "Referensial butunlik — bog'lanishlar har doim haqiqiy yozuvlarga "
            "ishora qilishini kafolatlash. Agar buyurtmada `customer_id = 7` "
            "yozilgan bo'lsa, `customers` jadvalida 7-raqamli mijoz **albatta** "
            "bo'lishi kerak.")

    para(d, "Buzilgan bog'lanish — yetim yozuv deb ataladi. U hisobotlarda "
            "noto'g'ri natija beradi, `JOIN` larda yo'qoladi va ilovada "
            "kutilmagan `null` ga aylanadi.")

    code(d, """CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL
        REFERENCES customers(id) ON DELETE RESTRICT,
    created_at  timestamptz NOT NULL DEFAULT now()
);""")

    note(d, "Bu kafolatni ilovaga yuklash nega yetarli emas:",
         "Kodda tekshiruv yozsam, u faqat mening ilovam orqali ketgan "
         "o'zgarishlarni qamrab oladi. Lekin bazaga migratsiya skriptlari, "
         "qo'lda yozilgan SQL, ma'lumot ko'chirish vositalari va boshqa "
         "tizimlar ham tegadi. Baza darajasidagi cheklov esa **har qanday** "
         "yo'ldan kelgan o'zgarishni tekshiradi.")

    # ───────────────────────────────────────────
    h1(d, "2. Tashqi kalit cheklovi")

    code(d, """ALTER TABLE orders
    ADD CONSTRAINT fk_orders_customer
    FOREIGN KEY (customer_id) REFERENCES customers(id)
    ON DELETE RESTRICT
    ON UPDATE CASCADE;""")

    para(d, "Cheklov ikki tomonni ham nazorat qiladi: yo'q mijozga ishora "
            "qiluvchi buyurtma qo'shib bo'lmaydi, va buyurtmasi bor mijozni "
            "o'chirib bo'lmaydi.")

    h2(d, "2.1 O'chirish xatti-harakatlari")

    table(d, ["Qiymat", "Ota yozuv o'chirilganda"],
          [["`RESTRICT`", "O'chirishga ruxsat berilmaydi (darhol tekshiriladi)"],
           ["`NO ACTION`", "Xuddi shunday, lekin tranzaksiya oxirida "
                           "tekshirilishi mumkin"],
           ["`CASCADE`", "Bog'liq yozuvlar ham o'chiriladi"],
           ["`SET NULL`", "Tashqi kalit `NULL` qilinadi"],
           ["`SET DEFAULT`", "Tashqi kalit sukutdagi qiymatga o'tadi"]],
          widths=[3.4, 12.1])

    note(d, "`CASCADE` bilan ehtiyot bo'lish kerak:",
         "U qulay ko'rinadi, lekin zanjir bo'ylab tarqaladi. Mijozni o'chirsam, "
         "uning buyurtmalari, ular bilan birga buyurtma qatorlari, to'lovlar "
         "va izohlar — hammasi o'chadi. Bitta `DELETE` buyrug'i minglab satrni "
         "yo'q qilishi mumkin va buni ortga qaytarib bo'lmaydi.")

    note(d, "Mening amaliy qoidam:",
         "Asosiy biznes jadvallarida `RESTRICT` qo'yaman — o'chirish ataylab "
         "qiyin bo'lsin. `CASCADE` ni esa faqat haqiqatan tobe ma'lumotlarda "
         "ishlataman: buyurtma qatorlari buyurtmasiz mavjud bo'lolmaydi, "
         "shuning uchun u yerda `CASCADE` mantiqiy.")

    h2(d, "2.2 EF Core dagi sukutdagi holat")

    code(d, """// Majburiy bog'lanish → sukut bo'yicha Cascade
builder.HasOne(o => o.Customer)
       .WithMany(c => c.Orders)
       .HasForeignKey(o => o.CustomerId);

// Aniq ko'rsatish
builder.HasOne(o => o.Customer)
       .WithMany(c => c.Orders)
       .HasForeignKey(o => o.CustomerId)
       .OnDelete(DeleteBehavior.Restrict);""")

    para(d, "Butun model bo'ylab bu sukutni o'zgartirish mumkin:")

    code(d, """foreach (var fk in modelBuilder.Model.GetEntityTypes()
                          .SelectMany(e => e.GetForeignKeys()))
{
    fk.DeleteBehavior = DeleteBehavior.Restrict;
}""")

    # ───────────────────────────────────────────
    h1(d, "3. Yumshoq o'chirish bilan ziddiyat")

    para(d, "Yumshoq o'chirishda yozuv aslida o'chirilmaydi, faqat "
            "`is_deleted` belgisi qo'yiladi. Bu referensial butunlikni "
            "saqlaydi, lekin yangi muammo tug'diradi.")

    code(d, """UPDATE customers SET is_deleted = true WHERE id = 7;
-- Tashqi kalit hamon ishlaydi, lekin...""")

    note(d, "Muammo shundaki, cheklov endi hech narsani tekshirmaydi:",
         "O'chirilgan mijozga yangi buyurtma qo'shish mumkin bo'lib qoladi — "
         "baza nuqtai nazaridan mijoz hamon mavjud. Ya'ni men referensial "
         "butunlikni saqladim, lekin **mantiqiy** butunlikni yo'qotdim.")

    para(d, "Buni qisman hal qilish uchun qisman indeks va cheklov "
            "ishlatiladi:")

    code(d, """-- Faqat faol mijozlar orasida email noyob bo'lsin
CREATE UNIQUE INDEX ux_customers_email_active
    ON customers (email)
    WHERE is_deleted = false;""")

    para(d, "Yangi buyurtma qo'shishda esa tekshiruvni ilova yoki trigger "
            "bajarishi kerak — tashqi kalit buni qila olmaydi.")

    # ───────────────────────────────────────────
    h1(d, "4. Indekslar va unumdorlik")

    para(d, "Tashqi kalit cheklovi ota jadvalda indeks talab qiladi (birlamchi "
            "kalit odatda bunga javob beradi), lekin **bola jadvalda** indeks "
            "avtomatik yaratilmaydi.")

    code(d, """-- Bu indeks avtomatik yaratilmaydi
CREATE INDEX ix_orders_customer_id ON orders (customer_id);""")

    note(d, "Indekssiz tashqi kalit sekinlik manbai bo'ladi:",
         "Mijozni o'chirmoqchi bo'lganimda baza \"shu mijozga bog'liq "
         "buyurtma bormi\" deb tekshiradi. Indeks bo'lmasa, u butun "
         "`orders` jadvalini skan qiladi. Bitta satrni o'chirish uchun "
         "million satr o'qiladi. PostgreSQL bu indeksni o'zi yaratmaydi, "
         "shuning uchun uni qo'shishni esda tutish kerak.")

    para(d, "EF Core esa tashqi kalit uchun indeksni avtomatik yaratadi — bu "
            "konventsiya `ForeignKeyIndexConvention` orqali ishlaydi.")

    # ───────────────────────────────────────────
    h1(d, "5. Kechiktirilgan tekshiruv")

    para(d, "Ba'zan ikki jadval bir-biriga ishora qiladi va qaysi birini "
            "birinchi qo'shish kerakligini aniqlab bo'lmaydi. Bunday holatda "
            "cheklovni tranzaksiya oxirigacha kechiktirish mumkin:")

    code(d, """ALTER TABLE departments
    ADD CONSTRAINT fk_departments_head
    FOREIGN KEY (head_employee_id) REFERENCES employees(id)
    DEFERRABLE INITIALLY DEFERRED;""")

    code(d, """BEGIN;
    INSERT INTO departments (id, name, head_employee_id) VALUES (1, 'IT', 100);
    INSERT INTO employees (id, name, department_id) VALUES (100, 'Ali', 1);
    -- Cheklovlar shu yerda tekshiriladi
COMMIT;""")

    # ───────────────────────────────────────────
    h1(d, "6. Mavjud ma'lumotni tekshirish")

    para(d, "Eski bazaga cheklov qo'shishdan oldin yetim yozuvlar borligini "
            "tekshirish kerak:")

    code(d, """-- Yetim buyurtmalarni topish
SELECT o.id, o.customer_id
FROM orders o
LEFT JOIN customers c ON c.id = o.customer_id
WHERE c.id IS NULL;""")

    code(d, """-- Barcha cheklovlarni ko'rish
SELECT conname, conrelid::regclass AS table_name, confrelid::regclass AS ref_table
FROM pg_constraint
WHERE contype = 'f'
ORDER BY conrelid::regclass::text;""")

    code(d, """-- Mavjud ma'lumotni tekshirmasdan cheklov qo'shish, keyin tekshirish
ALTER TABLE orders
    ADD CONSTRAINT fk_orders_customer
    FOREIGN KEY (customer_id) REFERENCES customers(id)
    NOT VALID;

-- Keyinroq, yuk kam paytda
ALTER TABLE orders VALIDATE CONSTRAINT fk_orders_customer;""")

    note(d, "`NOT VALID` katta jadvallarda juda foydali:",
         "Oddiy `ADD CONSTRAINT` butun jadvalni tekshiradi va shu davomida "
         "uni bloklaydi. Million satrli jadvalda bu bir necha daqiqa "
         "ishlamaslikni anglatadi. `NOT VALID` esa cheklovni darhol qo'yadi — "
         "u yangi satrlarga amal qiladi, eskilari esa keyinroq, alohida "
         "tekshiriladi.")

    # ───────────────────────────────────────────
    h1(d, "7. Cheklovsiz ishlash holatlari")

    para(d, "Ba'zi tizimlarda tashqi kalitlardan ataylab voz kechiladi. "
            "Sabablari:")

    bullets(d, [
        "Juda yuqori yozish tezligi talab qilinganda — cheklov har bir "
        "`INSERT` da tekshiruv qo'shadi.",
        "Ma'lumot bir nechta bazaga taqsimlangan (sharding) bo'lsa.",
        "Mikroservislarda — har bir xizmat o'z bazasiga ega va ular aro "
        "cheklov qo'yib bo'lmaydi.",
    ])

    note(d, "Lekin bu qaror ongli bo'lishi kerak:",
         "\"Tashqi kalit sekinlashtiradi\" degan fikr ko'pincha o'lchovsiz "
         "aytiladi. Odatiy yukda uning narxi sezilmaydi, foydasi esa katta. "
         "Men undan voz kechishdan oldin haqiqatan o'lchab ko'raman — "
         "aks holda men hech qachon bo'lmaydigan muammoni oldini olish uchun "
         "har kuni bo'ladigan muammoni sotib olgan bo'laman.")

    # ───────────────────────────────────────────
    h1(d, "8. Xulosa")

    bullets(d, [
        "Referensial butunlik bog'lanishlar haqiqiy yozuvlarga ishora "
        "qilishini kafolatlaydi.",
        "Baza cheklovi har qanday yo'ldan kelgan o'zgarishni tekshiradi — "
        "ilova kodi esa faqat o'zinikini.",
        "`RESTRICT` asosiy jadvallar uchun, `CASCADE` faqat tobe ma'lumotlar "
        "uchun.",
        "EF Core majburiy bog'lanishda sukut bo'yicha `Cascade` qo'yadi — "
        "buni ongli tekshirish kerak.",
        "Yumshoq o'chirish referensial butunlikni saqlaydi, lekin mantiqiy "
        "butunlikni emas.",
        "Tashqi kalit ustuniga indeks PostgreSQL da avtomatik yaratilmaydi.",
        "`DEFERRABLE` o'zaro ishora qiluvchi jadvallar uchun yechim beradi.",
        "`NOT VALID` katta jadvalga cheklovni bloklanishsiz qo'shish imkonini "
        "beradi.",
    ])

    sources(d, [
        ("Constraints — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/ddl-constraints.html"),
        ("ALTER TABLE — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/sql-altertable.html"),
        ("Cascade Delete — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/saving/cascade-delete"),
        ("Relationships — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/modeling/relationships"),
    ])
