# -*- coding: utf-8 -*-
from docbuild import *

TOPIC = "Table-per-type configuration"
CATEGORY = "EF Core"
TITLE = "TPT — Har Bir Tipga Alohida Jadval"
SUBTITLE = "Normallashtirilgan sxema va uning unumdorlikka ta'siri"
FILENAME = "Table-per-type configuration.docx"


def build(d):
    h1(d, "1. TPT ning ishlash prinsipi")

    para(d, "Table-per-Type strategiyasida ierarxiyaning har bir tipi — bazaviy tip ham, "
            "hosila tiplar ham — o'z jadvaliga ega bo'ladi. Bazaviy jadval umumiy "
            "ustunlarni saqlaydi, hosila jadvallar esa faqat o'z tipiga xos ustunlarni.")

    para(d, "Hosila jadvalning birlamchi kaliti ayni paytda bazaviy jadvalga ishora "
            "qiluvchi tashqi kalit ham bo'ladi. Ya'ni bitta mantiqiy yozuv ikkita jadvalda "
            "bir xil `Id` bilan saqlanadi va ular JOIN orqali birlashtiriladi.")

    para(d, "Bu yondashuv relyatsion normallashtirish qoidalariga eng mos keladigan "
            "variant — hech qanday ustun takrorlanmaydi va hech qanday katak sun'iy "
            "ravishda bo'sh qolmaydi.")

    # ───────────────────────────────────────────
    h1(d, "2. Sozlash")

    code(d, """public abstract class Vehicle
{
    public int Id { get; set; }
    public string PlateNumber { get; set; }
    public int Year { get; set; }
}

public class Truck : Vehicle
{
    public decimal LoadCapacityTons { get; set; }
    public int AxleCount { get; set; }
}

public class Motorcycle : Vehicle
{
    public int EngineCc { get; set; }
}""")

    para(d, "TPT ni yoqish uchun har bir tipga jadval nomi beriladi:")

    code(d, """modelBuilder.Entity<Vehicle>().ToTable("vehicles");
modelBuilder.Entity<Truck>().ToTable("trucks");
modelBuilder.Entity<Motorcycle>().ToTable("motorcycles");""")

    para(d, "EF Core 7 dan boshlab niyatni aniqroq ifodalash uchun alohida metod ham "
            "mavjud:")

    code(d, """modelBuilder.Entity<Vehicle>().UseTptMappingStrategy();""")

    para(d, "Bu holda jadval nomlari konventsiya bo'yicha klass nomlaridan olinadi.")

    h2(d, "2.1 Hosil bo'ladigan sxema")

    code(d, """CREATE TABLE "vehicles" (
    "Id"          integer GENERATED BY DEFAULT AS IDENTITY,
    "PlateNumber" text NOT NULL,
    "Year"        integer NOT NULL,
    CONSTRAINT "PK_vehicles" PRIMARY KEY ("Id")
);

CREATE TABLE "trucks" (
    "Id"               integer NOT NULL,
    "LoadCapacityTons" numeric NOT NULL,
    "AxleCount"        integer NOT NULL,
    CONSTRAINT "PK_trucks" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_trucks_vehicles_Id" FOREIGN KEY ("Id")
        REFERENCES "vehicles" ("Id") ON DELETE CASCADE
);

CREATE TABLE "motorcycles" (
    "Id"       integer NOT NULL,
    "EngineCc" integer NOT NULL,
    CONSTRAINT "PK_motorcycles" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_motorcycles_vehicles_Id" FOREIGN KEY ("Id")
        REFERENCES "vehicles" ("Id") ON DELETE CASCADE
);""")

    para(d, "E'tibor beriladigan ikki jihat: hosila jadvallarda `IDENTITY` yo'q — kalit "
            "bazaviy jadvaldan keladi; va ustunlar `NOT NULL` bo'lishi mumkin, chunki "
            "jadvalda faqat shu tipning yozuvlari bor.")

    note(d, "Mana shu meni TPT ga qiziqtirgan jihat:",
         "TPH da `LoadCapacityTons` ni majburiy qila olmayman, chunki mototsikl satrida "
         "u bo'sh bo'ladi. TPT da esa yuk mashinalari alohida jadvalda yotibdi va u yerda "
         "`NOT NULL` qo'yish butunlay mantiqiy. Ya'ni baza o'z ishini o'zi qilyapti.")

    # ───────────────────────────────────────────
    h1(d, "3. So'rovlar va generatsiya qilinadigan SQL")

    h2(d, "3.1 Bitta hosila tipni o'qish")

    code(d, """var trucks = await db.Set<Truck>().ToListAsync();""")

    code(d, """SELECT v."Id", v."PlateNumber", v."Year",
       t."LoadCapacityTons", t."AxleCount"
FROM "trucks" AS t
INNER JOIN "vehicles" AS v ON t."Id" = v."Id";""")

    para(d, "Bitta `INNER JOIN` — bu nisbatan arzon operatsiya, chunki birlashtirish "
            "birlamchi kalit bo'yicha ketyapti.")

    h2(d, "3.2 Butun ierarxiyani o'qish")

    code(d, """var all = await db.Vehicles.ToListAsync();""")

    code(d, """SELECT v."Id", v."PlateNumber", v."Year",
       t."LoadCapacityTons", t."AxleCount",
       m."EngineCc",
       CASE
           WHEN m."Id" IS NOT NULL THEN 'Motorcycle'
           WHEN t."Id" IS NOT NULL THEN 'Truck'
       END AS "Discriminator"
FROM "vehicles" AS v
LEFT JOIN "trucks" AS t ON v."Id" = t."Id"
LEFT JOIN "motorcycles" AS m ON v."Id" = m."Id";""")

    para(d, "Bu yerda TPT ning asosiy narxi ko'rinadi: har bir hosila tip uchun bitta "
            "`LEFT JOIN` qo'shiladi. Tiplar soni o'nga yetsa, so'rovda o'nta JOIN paydo "
            "bo'ladi.")

    note(d, "Buni albatta e'tiborga oling:",
         "Microsoft hujjatining o'zi TPT ni unumdorlik nuqtai nazaridan ogohlantirish "
         "bilan beradi — ko'p tipli ierarxiyada u sezilarli sekinlashishi mumkin. Men "
         "buni shunday tushunaman: agar ierarxiyada 3-4 tip bo'lsa va men ularni "
         "odatda alohida-alohida so'rasam, TPT muammo tug'dirmaydi. Agar 10 ta tip bo'lsa "
         "va men doim butun ro'yxatni olsam — bu har so'rovda 10 ta JOIN degani.")

    h2(d, "3.3 Faqat kerakli maydonlarni olish")

    para(d, "JOIN sonini kamaytirishning eng oddiy yo'li — proyeksiya. Agar so'rovda "
            "faqat bazaviy tipning maydonlari kerak bo'lsa, EF Core hosila jadvallarga "
            "umuman tegmaydi:")

    code(d, """var plates = await db.Vehicles
    .Select(v => new { v.Id, v.PlateNumber })
    .ToListAsync();

// SELECT v."Id", v."PlateNumber" FROM "vehicles" AS v   — JOIN yo'q""")

    note(d, "Bu menga ancha yordam beradi:",
         "Ro'yxat sahifalarida odatda faqat bir nechta umumiy maydon ko'rsatiladi. "
         "O'sha yerda proyeksiya ishlatsam, TPT ning JOIN narxi butunlay yo'qoladi. "
         "To'liq entity esa faqat bitta yozuvning tafsilotini ochganda kerak bo'ladi — "
         "u yerda esa bitta JOIN muammo emas.")

    # ───────────────────────────────────────────
    h1(d, "4. Yozish operatsiyalari")

    code(d, """db.Add(new Truck
{
    PlateNumber = "01A123BC",
    Year = 2021,
    LoadCapacityTons = 12.5m,
    AxleCount = 3
});
await db.SaveChangesAsync();""")

    para(d, "EF Core ikkita `INSERT` yuboradi — avval `vehicles` ga, keyin olingan `Id` "
            "bilan `trucks` ga. Ikkalasi bitta tranzaksiya ichida bajariladi.")

    para(d, "O'chirishda esa `ON DELETE CASCADE` tufayli bazaviy satrni o'chirish hosila "
            "satrni ham o'chiradi.")

    # ───────────────────────────────────────────
    h1(d, "5. Jadval va ustun nomlarini boshqarish")

    code(d, """modelBuilder.Entity<Vehicle>(e =>
{
    e.ToTable("vehicles", schema: "fleet");
    e.Property(v => v.PlateNumber).HasColumnName("plate_number");
});

modelBuilder.Entity<Truck>(e =>
{
    e.ToTable("trucks", schema: "fleet");
    e.Property(t => t.LoadCapacityTons).HasColumnName("load_capacity_tons");
});""")

    para(d, "Hosila tiplardagi bir xil nomli xossalar TPT da to'qnashmaydi — ular "
            "turli jadvallarda joylashadi.")

    # ───────────────────────────────────────────
    h1(d, "6. TPT ni qachon tanlayman")

    para(d, "TPT foydali bo'ladigan holatlar:")

    bullets(d, [
        "Hosila tiplarda ko'p sonli va **majburiy** maydonlar bo'lsa.",
        "Baza sxemasi boshqa jamoalar yoki hisobot tizimlari tomonidan ham o'qilsa — "
        "TPT sxemasi o'zini o'zi tushuntiradi.",
        "Tiplar soni kam (2-4 ta) va ular odatda alohida so'ralsa.",
        "Ma'lumot takrorlanishi mutlaqo qabul qilinmasa.",
    ])

    para(d, "TPT dan voz kechadigan holatlar:")

    bullets(d, [
        "Ierarxiyada ko'p tip bo'lsa va butun ro'yxat tez-tez so'ralsa.",
        "O'qish unumdorligi asosiy talab bo'lsa — o'shanda TPH yoki TPC afzalroq.",
    ])

    note(d, "Mening yakuniy fikrim:",
         "TPT — sxema tozaligi uchun unumdorlikdan voz kechish. Bu adolatli kelishuv, "
         "lekin uni ongli qilish kerak. Men TPT ni tanlasam, ro'yxat so'rovlarini "
         "albatta proyeksiya bilan yozaman — aks holda strategiyaning narxini har "
         "sahifada to'lab yuraman.")

    # ───────────────────────────────────────────
    h1(d, "7. Xulosa")

    bullets(d, [
        "TPT da har bir tip o'z jadvaliga ega; hosila jadvalning kaliti bazaviy "
        "jadvalga tashqi kalit bo'ladi.",
        "`ToTable()` yoki `UseTptMappingStrategy()` bilan yoqiladi.",
        "Hosila tiplarning maydonlariga `NOT NULL` qo'yish mumkin — TPH da bu imkonsiz.",
        "Butun ierarxiyani o'qish har bir hosila tip uchun bitta `LEFT JOIN` qo'shadi.",
        "Proyeksiya ishlatilsa, keraksiz JOIN lar umuman generatsiya qilinmaydi.",
        "Bitta yozuvni qo'shish ikkita `INSERT` ga aylanadi.",
    ])

    sources(d, [
        ("Inheritance: Table-per-type configuration — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/modeling/inheritance#table-per-type-configuration"),
        ("Table Splitting and Inheritance performance — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/performance/modeling-for-performance"),
    ])
