# -*- coding: utf-8 -*-
from docbuild import *

TOPIC = "Atomicity principle"
CATEGORY = "Database Design Principles"
TITLE = "Atomiclik Tamoyili"
SUBTITLE = "Bo'linmas qiymatlar va bo'linmas amallar"
FILENAME = "Atomicity principle.docx"


def build(d):
    h1(d, "1. Atomiclik ikki ma'noda")

    para(d, "Ma'lumotlar bazasini loyihalashda \"atomiclik\" so'zi ikki turli "
            "kontekstda ishlatiladi va ularni ajratish muhim:")

    bullets(d, [
        "**Qiymat atomikligi** — har bir katakda bitta, bo'linmas qiymat "
        "turishi. Bu normallashtirishning birinchi shakli (1NF) talabi.",
        "**Amal atomikligi** — tranzaksiya to'liq bajarilishi yoki umuman "
        "bajarilmasligi. Bu ACID dagi A harfi.",
    ])

    para(d, "Bu hujjat asosan birinchi ma'noga, ya'ni loyihalash tamoyiliga "
            "bag'ishlangan; ikkinchisi tranzaksiyalar mavzusida batafsil "
            "ko'rib chiqiladi.")

    # ───────────────────────────────────────────
    h1(d, "2. Qiymat atomikligi")

    para(d, "Tamoyil shuni talab qiladi: ustun qiymati ilova uchun mantiqan "
            "bo'linmas bo'lishi kerak. Agar men qiymatning bir qismi bilan "
            "ishlashim kerak bo'lsa, demak u atomik emas.")

    h2(d, "2.1 Buzilishning tipik ko'rinishlari")

    code(d, """-- Buzilgan: bir katakda bir nechta qiymat
CREATE TABLE users (
    id       bigint PRIMARY KEY,
    name     text,
    phones   text          -- '+998901234567, +998339876543'
);

-- Buzilgan: tuzilgan qiymat bitta ustunda
CREATE TABLE orders (
    id       bigint PRIMARY KEY,
    address  text          -- 'Toshkent, Chilonzor, 12-uy, 45-xonadon'
);

-- Buzilgan: takrorlanuvchi ustunlar
CREATE TABLE students (
    id       bigint PRIMARY KEY,
    course1  text,
    course2  text,
    course3  text
);""")

    para(d, "Uchala holat ham bir xil muammoga olib keladi — qiymat ichidagi "
            "qismga so'rov yozish imkonsiz yoki juda noqulay bo'ladi.")

    code(d, """-- Vergul bilan saqlangan telefonlarni qidirish
SELECT * FROM users WHERE phones LIKE '%901234567%';

-- Bu so'rov indeksdan foydalana olmaydi va noto'g'ri natija berishi mumkin
-- (masalan, boshqa raqamning o'rtasiga mos kelsa)""")

    h2(d, "2.2 To'g'ri tuzilma")

    code(d, """CREATE TABLE users (
    id    bigint PRIMARY KEY,
    name  text NOT NULL
);

CREATE TABLE user_phones (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    phone    text NOT NULL,
    is_primary boolean NOT NULL DEFAULT false
);

CREATE INDEX ix_user_phones_phone ON user_phones (phone);""")

    code(d, """-- Endi qidiruv indeksdan foydalanadi va aniq
SELECT u.*
FROM users u
JOIN user_phones p ON p.user_id = u.id
WHERE p.phone = '+998901234567';""")

    note(d, "Bu tuzatish qo'shimcha imkoniyat ham beradi:",
         "Alohida jadvalda telefon raqamiga `is_primary`, `verified_at`, "
         "`type` kabi maydonlar qo'shish mumkin. Vergul bilan ajratilgan "
         "matnda bunday ma'lumotni saqlashning iloji yo'q. Ya'ni atomiclik "
         "faqat \"to'g'ri\" bo'lish uchun emas, kengayish uchun ham kerak.")

    # ───────────────────────────────────────────
    h1(d, "3. Atomiclik kontekstga bog'liq")

    para(d, "Qiymat atomikmi yoki yo'qmi — bu mutlaq savol emas. Javob ilova "
            "unga qanday murojaat qilishiga bog'liq.")

    table(d, ["Qiymat", "Atomik bo'ladi", "Atomik bo'lmaydi"],
          [["To'liq ism", "Faqat ko'rsatish uchun ishlatilsa",
            "Ism va familiya bo'yicha alohida qidirilsa"],
           ["Manzil matni", "Faqat chop etish uchun",
            "Shahar bo'yicha filtrlansa"],
           ["Sana va vaqt", "Odatda atomik",
            "Faqat kun qismi tez-tez kerak bo'lsa"]],
          widths=[3.6, 6.0, 5.9])

    note(d, "Shuning uchun men savolni boshqacha qo'yaman:",
         "\"Bu qiymat atomikmi?\" emas, balki \"men bu qiymatning bir qismi "
         "bo'yicha qidirish, saralash yoki guruhlashim kerak bo'ladimi?\" deb "
         "so'rayman. Agar javob \"ha\" bo'lsa — uni ajratish kerak. Agar "
         "\"yo'q\" bo'lsa — ajratish ortiqcha murakkablik bo'ladi.")

    # ───────────────────────────────────────────
    h1(d, "4. Massiv va JSON ustunlar")

    para(d, "PostgreSQL massiv va `jsonb` tiplarini qo'llab-quvvatlaydi. Bu "
            "atomiclik tamoyilini buzishdek ko'rinadi, lekin vaziyat biroz "
            "murakkabroq.")

    code(d, """CREATE TABLE articles (
    id    bigint PRIMARY KEY,
    title text NOT NULL,
    tags  text[] NOT NULL DEFAULT '{}',
    meta  jsonb
);

CREATE INDEX ix_articles_tags ON articles USING GIN (tags);
CREATE INDEX ix_articles_meta ON articles USING GIN (meta);""")

    code(d, """-- Indeksdan foydalanadigan so'rovlar
SELECT * FROM articles WHERE tags @> ARRAY['dotnet'];
SELECT * FROM articles WHERE meta @> '{"featured": true}';""")

    para(d, "Vergul bilan ajratilgan matndan farqli o'laroq, bu yerda baza "
            "tuzilmani tushunadi va indeks qo'llay oladi. Shuning uchun bu "
            "texnik jihatdan 1NF buzilishi bo'lsa-da, amaliy muammolarni "
            "keltirib chiqarmaydi.")

    note(d, "Lekin men ularni ehtiyotkorlik bilan ishlataman:",
         "JSON ustun — bu sxemani keyinga qoldirish. Agar men `meta` ichiga "
         "muhim maydonlarni yashirsam, ularda `NOT NULL`, tashqi kalit yoki "
         "tip tekshiruvi bo'lmaydi. Shuning uchun qoidam oddiy: **ma'lum va "
         "doimiy** maydonlar — ustun, **o'zgaruvchan yoki ixtiyoriy** "
         "qo'shimchalar — JSON.")

    table(d, ["Ustun afzal", "JSON afzal"],
          [["Har bir yozuvda mavjud", "Faqat ba'zi yozuvlarda bor"],
           ["Bo'yicha tez-tez qidiriladi", "Kamdan-kam qidiriladi"],
           ["Tashqi kalit kerak", "Bog'lanish kerak emas"],
           ["Tuzilmasi barqaror", "Tuzilmasi tez-tez o'zgaradi"]],
          widths=[7.7, 7.8])

    # ───────────────────────────────────────────
    h1(d, "5. Amal atomikligi — qisqacha")

    para(d, "Ikkinchi ma'no — bir nechta o'zgarish bo'linmas birlik sifatida "
            "bajarilishi. Bu tranzaksiya orqali ta'minlanadi.")

    code(d, """BEGIN;
    INSERT INTO orders (customer_id, total) VALUES (7, 150000);
    INSERT INTO order_items (order_id, product_id, quantity)
        VALUES (currval('orders_id_seq'), 42, 3);
    UPDATE products SET stock = stock - 3 WHERE id = 42;
COMMIT;""")

    para(d, "Loyihalash nuqtai nazaridan muhim xulosa shuki, birga "
            "o'zgarishi kerak bo'lgan ma'lumotlar bitta bazada bo'lishi "
            "maqsadga muvofiq. Agar ular turli bazalarga tarqalsa, atomiclikni "
            "ta'minlash ancha murakkablashadi.")

    note(d, "Mikroservislarda bu masala jiddiy:",
         "Buyurtma bir xizmatda, ombor boshqasida bo'lsa, ularni bitta "
         "tranzaksiyada o'zgartirib bo'lmaydi. Yechim sifatida saga naqshi "
         "ishlatiladi — har bir qadam alohida bajariladi va xato bo'lsa, "
         "kompensatsiya amali qo'llanadi. Bu ishlaydi, lekin oddiy "
         "tranzaksiyadan ancha murakkab. Shuning uchun xizmatlar chegarasini "
         "belgilashda \"nima birga o'zgaradi\" degan savol muhim.")

    # ───────────────────────────────────────────
    h1(d, "6. Tekshirish ro'yxati")

    bullets(d, [
        "Vergul yoki boshqa ajratuvchi bilan saqlangan ro'yxatlar bormi.",
        "`field1`, `field2`, `field3` ko'rinishidagi takrorlanuvchi ustunlar "
        "bormi.",
        "`LIKE '%...%'` bilan qidiriladigan ustunlar bormi — bu ko'pincha "
        "atomiclik buzilganining belgisi.",
        "JSON ustun ichida majburiy maydonlar yashiringanmi.",
        "Birga o'zgarishi kerak bo'lgan jadvallar bitta bazada turibdimi.",
    ])

    # ───────────────────────────────────────────
    h1(d, "7. Xulosa")

    bullets(d, [
        "Atomiclik ikki ma'noda: qiymat bo'linmasligi (1NF) va amal "
        "bo'linmasligi (ACID).",
        "Bir katakda bir nechta qiymat saqlash qidiruv va indekslashni "
        "buzadi.",
        "Takrorlanuvchi ustunlar o'rniga alohida jadval ishlatiladi.",
        "Atomiklik mutlaq emas — u ilovaning qiymatdan qanday "
        "foydalanishiga bog'liq.",
        "Massiv va `jsonb` tuzilgan tiplar bo'lgani uchun indekslanadi va "
        "matnli ro'yxatdan farq qiladi.",
        "Barqaror va majburiy maydonlar ustun bo'lishi, o'zgaruvchan "
        "qo'shimchalar JSON da qolishi mumkin.",
        "Birga o'zgaradigan ma'lumotlar bitta bazada bo'lgani atomiclikni "
        "ta'minlashni osonlashtiradi.",
    ])

    sources(d, [
        ("Database normalization basics — Microsoft",
         "https://learn.microsoft.com/en-us/office/troubleshoot/access/database-normalization-description"),
        ("JSON Types — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/datatype-json.html"),
        ("Arrays — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/arrays.html"),
        ("Saga distributed transactions pattern",
         "https://learn.microsoft.com/en-us/azure/architecture/patterns/saga"),
    ])
