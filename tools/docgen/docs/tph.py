# -*- coding: utf-8 -*-
from docbuild import *

TOPIC = "Table-per-hierarchy and discriminator configuration"
CATEGORY = "EF Core"
TITLE = "TPH va Diskriminator Sozlamalari"
SUBTITLE = "Butun ierarxiyani bitta jadvalga joylash"
FILENAME = "Table-per-hierarchy and discriminator configuration.docx"


def build(d):
    h1(d, "1. TPH ning ishlash prinsipi")

    para(d, "Table-per-Hierarchy strategiyasida bazaviy tip va undan kelib chiqqan barcha "
            "tiplar bitta jadvalga joylashtiriladi. Jadval ierarxiyadagi barcha tiplarning "
            "ustunlarini o'z ichiga oladi, har bir satr esa faqat o'z tipiga tegishli "
            "ustunlarni to'ldiradi; qolganlari `NULL` bo'lib qoladi.")

    para(d, "Satr qaysi tipga tegishli ekanini aniqlash uchun jadvalga qo'shimcha "
            "diskriminator ustuni kiritiladi. EF Core har bir so'rovga shu ustun bo'yicha "
            "filtr qo'shadi va o'qilgan satrni to'g'ri C# tipiga aylantiradi.")

    para(d, "TPH — EF Core dagi sukutdagi strategiya. Agar ierarxiya uchun hech qanday "
            "sozlama berilmasa, aynan shu usul qo'llanadi.")

    # ───────────────────────────────────────────
    h1(d, "2. Oddiy misol")

    code(d, """public abstract class Notification
{
    public int Id { get; set; }
    public string Recipient { get; set; }
    public DateTime CreatedAt { get; set; }
    public bool IsSent { get; set; }
}

public class EmailNotification : Notification
{
    public string Subject { get; set; }
    public string HtmlBody { get; set; }
}

public class SmsNotification : Notification
{
    public string Text { get; set; }
}""")

    code(d, """public DbSet<Notification> Notifications => Set<Notification>();""",
         caption="Kontekstda faqat bazaviy tip e'lon qilinadi")

    para(d, "Qo'shimcha sozlamasiz EF Core quyidagi jadvalni yaratadi:")

    code(d, """CREATE TABLE "Notifications" (
    "Id"            integer GENERATED BY DEFAULT AS IDENTITY,
    "Recipient"     text NOT NULL,
    "CreatedAt"     timestamp with time zone NOT NULL,
    "IsSent"        boolean NOT NULL,
    "Discriminator" text NOT NULL,
    "Subject"       text NULL,
    "HtmlBody"      text NULL,
    "Text"          text NULL,
    CONSTRAINT "PK_Notifications" PRIMARY KEY ("Id")
);""")

    note(d, "Birinchi marta ko'rganimda e'tibor berganim:",
         "`Subject`, `HtmlBody` va `Text` ustunlari `NULL` bo'lishi kerakligi majburiy. "
         "Hatto men C# da `string Subject` deb nullable bo'lmagan qilib yozsam ham, "
         "baza darajasida u baribir nullable bo'ladi. Sababi tushunarli — SMS satrida "
         "`Subject` bo'lmaydi-ku. Lekin bu shuni anglatadiki, majburiylikni endi faqat "
         "ilova kodim ta'minlaydi.")

    # ───────────────────────────────────────────
    h1(d, "3. Diskriminator sozlamalari")

    h2(d, "3.1 Sukutdagi holat")

    para(d, "Sozlanmagan holda diskriminator ustuni `Discriminator` deb nomlanadi, "
            "`string` tipida bo'ladi va qiymat sifatida C# klassining nomini saqlaydi — "
            "`EmailNotification`, `SmsNotification`.")

    h2(d, "3.2 Nom va qiymatlarni o'zgartirish")

    code(d, """modelBuilder.Entity<Notification>()
    .HasDiscriminator<string>("channel")
    .HasValue<EmailNotification>("email")
    .HasValue<SmsNotification>("sms");""")

    para(d, "Qisqa qiymatlar jadval hajmini kamaytiradi va bazaga qo'lda so'rov "
            "yozganda o'qishni osonlashtiradi.")

    h2(d, "3.3 Butun son diskriminator")

    code(d, """modelBuilder.Entity<Notification>()
    .HasDiscriminator<int>("ChannelId")
    .HasValue<EmailNotification>(1)
    .HasValue<SmsNotification>(2);""")

    note(d, "Bu yerda ehtiyot bo'lish kerak:",
         "Butun son indeks uchun biroz tejamkorroq, lekin bazaga qarab turib `1` nima "
         "ekanini bilish uchun har safar kodga murojaat qilishga to'g'ri keladi. Men "
         "odatda qisqa matnni tanlayman — `email` yoki `sms` deb yozilsa, hech qanday "
         "izoh kerak emas. Tejalgan baytlar bu noqulaylikka arzimaydi.")

    note(d, "Eng muhim qoida:",
         "Diskriminator qiymatini keyinchalik o'zgartirib bo'lmaydi. Agar men bugun "
         "`EmailNotification` ni `email` deb belgilasam va bir yildan keyin uni "
         "`e-mail` ga o'zgartirsam, bazadagi barcha eski satrlar o'qilmay qoladi — "
         "EF Core ularning tipini aniqlay olmaydi. Shuning uchun bu qiymatlarni "
         "boshidanoq ongli tanlash kerak.")

    h2(d, "3.4 Diskriminatorni xossa sifatida ochish")

    para(d, "Odatda diskriminator shadow property bo'ladi — C# klassida ko'rinmaydi. "
            "Lekin uni oddiy xossaga bog'lash ham mumkin:")

    code(d, """public abstract class Notification
{
    public string Channel { get; set; }   // diskriminator
    ...
}

modelBuilder.Entity<Notification>()
    .HasDiscriminator(n => n.Channel)
    .HasValue<EmailNotification>("email")
    .HasValue<SmsNotification>("sms");""")

    para(d, "Bu holda qiymat kod ichidan o'qiladigan bo'ladi, lekin uni qo'lda "
            "o'zgartirishga urinish xatolikka olib keladi — EF Core bu ustunni o'zi "
            "boshqaradi.")

    h2(d, "3.5 Diskriminator to'liqligi")

    para(d, "EF Core 7 dan boshlab so'rovga `Discriminator IN (...)` sharti qo'shilmasligi "
            "mumkin — agar EF Core jadvalda boshqa tip yo'qligiga ishonsa. Bu xatti-harakat "
            "quyidagicha boshqariladi:")

    code(d, """modelBuilder.Entity<Notification>()
    .HasDiscriminator<string>("channel")
    .IsComplete(false);   // jadvalda noma'lum tiplar ham bo'lishi mumkin""")

    para(d, "`IsComplete(false)` qo'yilsa, EF Core har doim aniq filtr qo'shadi. Bu "
            "jadvalni boshqa tizim bilan bo'lishganda kerak bo'ladi.")

    # ───────────────────────────────────────────
    h1(d, "4. So'rovlar qanday ishlaydi")

    code(d, """// Barcha xabarnomalar — filtrsiz
var all = await db.Notifications.ToListAsync();
// SELECT ... FROM "Notifications"

// Faqat email
var emails = await db.Notifications.OfType<EmailNotification>().ToListAsync();
// SELECT ... FROM "Notifications" WHERE "channel" = 'email'

// Hosila tipning maydoni bo'yicha filtr
var urgent = await db.Notifications
    .OfType<EmailNotification>()
    .Where(e => e.Subject.Contains("Shoshilinch"))
    .ToListAsync();""")

    para(d, "Hech qanday JOIN yo'q — bu TPH ning asosiy unumdorlik afzalligi. Qo'shilgan "
            "`WHERE` sharti indeks bilan samarali ishlaydi.")

    h2(d, "4.1 Diskriminator bo'yicha indeks")

    para(d, "Agar ierarxiyada bir tip boshqalaridan sezilarli ko'p bo'lsa, diskriminator "
            "ustuniga indeks qo'yish foyda beradi:")

    code(d, """modelBuilder.Entity<Notification>()
    .HasIndex("channel");

// Yoki ko'p ishlatiladigan filtr bilan birga:
modelBuilder.Entity<Notification>()
    .HasIndex("channel", nameof(Notification.IsSent));""")

    # ───────────────────────────────────────────
    h1(d, "5. Ustun nomlarining to'qnashuvi")

    para(d, "Ikki hosila tipda bir xil nomli, lekin turli ma'noli xossa bo'lsa, ular bitta "
            "ustunga tushib qolishga urinadi va EF Core xatolik beradi. Yechim — ustun "
            "nomlarini aniq ajratish:")

    code(d, """modelBuilder.Entity<EmailNotification>()
    .Property(e => e.Body).HasColumnName("email_body");

modelBuilder.Entity<SmsNotification>()
    .Property(s => s.Body).HasColumnName("sms_body");""")

    para(d, "Agar ikkala xossa bir xil tipda bo'lsa va ma'nosi ham bir xil bo'lsa, ularni "
            "bitta ustunda qoldirish mumkin — bu jadval kengligini kamaytiradi.")

    # ───────────────────────────────────────────
    h1(d, "6. TPH ning kuchli va zaif tomonlari")

    para(d, "Kuchli tomonlari:")

    bullets(d, [
        "Hech qanday JOIN yo'q — eng tez o'qish.",
        "Barcha tiplarni bir yo'la olish bitta oddiy `SELECT` bilan bajariladi.",
        "Yangi hosila tip qo'shish — jadvalga bir nechta nullable ustun qo'shish, bu "
        "migration sifatida ham xavfsiz operatsiya.",
        "Bazaviy tipga tashqi kalit qo'yish muammosiz ishlaydi.",
    ])

    para(d, "Zaif tomonlari:")

    bullets(d, [
        "Hosila tiplarning maydonlarida `NOT NULL` cheklovini qo'yib bo'lmaydi.",
        "Tiplar soni ortgani sayin jadval kengayib boradi va bo'sh kataklar ko'payadi.",
        "Bazaga tashqaridan qaragan odam uchun sxema tushunarsizroq bo'ladi.",
    ])

    note(d, "Mening amaliy xulosam:",
         "NOT NULL yo'qligi menga dastlab katta kamchilik bo'lib tuyulgandi. Lekin "
         "amalda bu cheklovni baribir ilova darajasida ham tekshiraman — validatsiya, "
         "DTO, konstruktor orqali. Ya'ni baza cheklovi menda ikkinchi himoya qatlami "
         "vazifasini bajaradi, birinchisi emas. Shuning uchun ko'p holatda TPH ni "
         "tanlashda ikkilanmayman.")

    note(d, "Qachon TPH dan voz kechaman:",
         "Agar bazaga faqat mening ilovam emas, boshqa tizimlar ham yozsa. O'shanda "
         "cheklovlarni baza o'zi ushlashi kerak va TPH buni qila olmaydi.")

    # ───────────────────────────────────────────
    h1(d, "7. NOT NULL ni qisman tiklash")

    para(d, "To'liq bo'lmasa-da, baza darajasida shartli cheklov qo'yish mumkin:")

    code(d, """modelBuilder.Entity<Notification>()
    .ToTable(t => t.HasCheckConstraint(
        "CK_notifications_email_subject",
        "\\"channel\\" <> 'email' OR \\"Subject\\" IS NOT NULL"));""")

    para(d, "Bu cheklov \"agar kanal email bo'lsa, Subject bo'sh bo'lmasin\" degan qoidani "
            "bazaning o'ziga yuklaydi. Har bir majburiy maydon uchun alohida yozish kerak "
            "bo'ladi, shuning uchun uni faqat haqiqatan kritik maydonlarga qo'llayman.")

    # ───────────────────────────────────────────
    h1(d, "8. Xulosa")

    bullets(d, [
        "TPH — EF Core dagi sukutdagi strategiya: butun ierarxiya bitta jadvalda.",
        "Diskriminator ustuni satrning tipini aniqlaydi; uning nomi va qiymatlari "
        "`HasDiscriminator` bilan sozlanadi.",
        "Diskriminator qiymatlarini keyinchalik o'zgartirib bo'lmaydi — bu mavjud "
        "ma'lumotni o'qib bo'lmaydigan qiladi.",
        "Hosila tiplarning ustunlari majburan nullable bo'ladi; kerak bo'lsa "
        "`CHECK` cheklovi bilan qisman qoplanadi.",
        "JOIN yo'qligi TPH ni o'qish bo'yicha eng tez strategiyaga aylantiradi.",
    ])

    sources(d, [
        ("Inheritance: Table-per-hierarchy — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/modeling/inheritance#table-per-hierarchy-and-discriminator-configuration"),
        ("Tables and Check Constraints — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/modeling/relational/tables"),
    ])
