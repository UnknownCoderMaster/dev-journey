# -*- coding: utf-8 -*-
from docbuild import *

TOPIC = "Trigger va Sequence"
CATEGORY = "SQL"
TITLE = "Trigger va Sequence"
SUBTITLE = "Avtomatik bajariladigan amallar va raqam generatorlari"
FILENAME = "Trigger va Sequence.docx"


def build(d):
    h1(d, "1. Sequence")

    para(d, "Sequence — ketma-ket noyob sonlar generatori. U jadvaldan mustaqil "
            "obyekt bo'lib, bir nechta jadval bitta sequence dan foydalanishi "
            "ham mumkin.")

    code(d, """CREATE SEQUENCE order_number_seq
    START WITH 1000
    INCREMENT BY 1
    MINVALUE 1000
    NO MAXVALUE
    CACHE 20;""")

    table(d, ["Parametr", "Vazifasi"],
          [["`START WITH`", "Boshlang'ich qiymat"],
           ["`INCREMENT BY`", "Qadam; manfiy ham bo'lishi mumkin"],
           ["`CACHE`", "Xotirada oldindan ajratiladigan qiymatlar soni"],
           ["`CYCLE`", "Chegaraga yetganda boshidan boshlash"],
           ["`OWNED BY`", "Ustunga bog'lash — ustun o'chsa, sequence ham o'chadi"]],
          widths=[4.0, 11.5])

    code(d, """SELECT nextval('order_number_seq');   -- 1000, keyingi safar 1001
SELECT currval('order_number_seq');   -- shu sessiyadagi oxirgi qiymat
SELECT setval('order_number_seq', 5000);""")

    h2(d, "1.1 Identity va serial")

    para(d, "Amalda sequence ko'pincha to'g'ridan-to'g'ri emas, ustun ta'rifi "
            "orqali ishlatiladi:")

    code(d, """-- Zamonaviy, standartga mos usul
CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ...
);

-- Eski usul (PostgreSQL ga xos)
CREATE TABLE orders (
    id bigserial PRIMARY KEY,
    ...
);""")

    para(d, "`GENERATED ALWAYS` qiymatni qo'lda berishni umuman taqiqlaydi, "
            "`GENERATED BY DEFAULT` esa ruxsat beradi. Ikkinchisi ma'lumot "
            "ko'chirishda qulayroq.")

    h2(d, "1.2 Muhim xususiyat — bo'shliqlar")

    note(d, "Buni bilmasdan turib hisobot yozish xato bo'ladi:",
         "Sequence qiymatlari **ketma-ket bo'lishi kafolatlanmaydi**. "
         "Tranzaksiya bekor qilinsa, olingan raqam qaytarilmaydi. `CACHE` "
         "yoqilgan bo'lsa, server qayta ishga tushganda keshdagi qolgan "
         "qiymatlar yo'qoladi. Ya'ni 1000, 1001, 1005, 1006 degan ketma-ketlik "
         "butunlay normal holat.")

    para(d, "Shuning uchun hujjat raqamlari uzluksiz bo'lishi talab qilinsa, "
            "sequence yaramaydi. Bunday holatda alohida jadval va qulf "
            "ishlatiladi:")

    code(d, """-- Uzluksiz raqam kerak bo'lganda
UPDATE document_counters
SET last_number = last_number + 1
WHERE document_type = 'invoice'
RETURNING last_number;""")

    para(d, "Bu usul ketma-ketlikni kafolatlaydi, lekin parallel so'rovlarni "
            "navbatga qo'yadi va unumdorlikni cheklaydi.")

    h2(d, "1.3 EF Core da sequence")

    code(d, """modelBuilder.HasSequence<int>("order_number_seq")
    .StartsAt(1000)
    .IncrementsBy(1);

modelBuilder.Entity<Order>()
    .Property(o => o.Number)
    .HasDefaultValueSql("nextval('order_number_seq')");""")

    # ───────────────────────────────────────────
    h1(d, "2. Trigger")

    para(d, "Trigger — jadvalda ma'lum hodisa yuz berganda avtomatik "
            "bajariladigan funksiya. Hodisa `INSERT`, `UPDATE`, `DELETE` yoki "
            "`TRUNCATE` bo'lishi mumkin.")

    h2(d, "2.1 Tuzilmasi")

    para(d, "PostgreSQL da trigger ikki qismdan iborat: avval funksiya "
            "yaratiladi, keyin u jadvalga bog'lanadi.")

    code(d, """CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER orders_set_updated_at
    BEFORE UPDATE ON orders
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();""")

    h2(d, "2.2 Vaqt va qamrov")

    table(d, ["Parametr", "Variantlar", "Ma'nosi"],
          [["Vaqt", "`BEFORE`", "Amaldan oldin; `NEW` ni o'zgartirish mumkin"],
           ["", "`AFTER`", "Amaldan keyin; o'zgartirib bo'lmaydi"],
           ["", "`INSTEAD OF`", "Amal o'rniga; faqat `VIEW` uchun"],
           ["Qamrov", "`FOR EACH ROW`", "Har bir satr uchun"],
           ["", "`FOR EACH STATEMENT`", "Butun buyruq uchun bir marta"]],
          widths=[2.8, 4.6, 8.1])

    h2(d, "2.3 NEW va OLD")

    code(d, """CREATE OR REPLACE FUNCTION log_price_change()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.price IS DISTINCT FROM OLD.price THEN
        INSERT INTO price_history (product_id, old_price, new_price, changed_at)
        VALUES (OLD.id, OLD.price, NEW.price, now());
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER products_log_price
    AFTER UPDATE OF price ON products
    FOR EACH ROW
    EXECUTE FUNCTION log_price_change();""")

    table(d, ["O'zgaruvchi", "`INSERT`", "`UPDATE`", "`DELETE`"],
          [["`NEW`", "Yangi satr", "Yangi qiymatlar", "`NULL`"],
           ["`OLD`", "`NULL`", "Eski qiymatlar", "O'chirilayotgan satr"]],
          widths=[3.4, 4.0, 4.1, 4.0])

    note(d, "`IS DISTINCT FROM` ni ishlatish sababi:",
         "Oddiy `<>` operatori `NULL` bilan solishtirilganda `NULL` qaytaradi "
         "va shart bajarilmaydi. Ya'ni narx `NULL` dan `5000` ga o'zgarsa, "
         "`OLD.price <> NEW.price` sharti ishlamaydi. `IS DISTINCT FROM` esa "
         "`NULL` larni ham to'g'ri taqqoslaydi.")

    # ───────────────────────────────────────────
    h1(d, "3. Trigger ning tipik qo'llanishlari")

    bullets(d, [
        "**Audit jurnali** — kim, qachon, nimani o'zgartirgani.",
        "**Vaqt belgilarini avtomatik to'ldirish** — `created_at`, "
        "`updated_at`.",
        "**Hosila qiymatlarni yangilash** — yig'indi, hisoblagichlar.",
        "**Murakkab cheklovlar** — `CHECK` bilan ifodalab bo'lmaydiganlari.",
        "**Yumshoq o'chirishni amalga oshirish.**",
    ])

    code(d, """-- Buyurtma summasini qatorlar asosida yangilash
CREATE OR REPLACE FUNCTION recalc_order_total()
RETURNS TRIGGER AS $$
DECLARE
    target_order bigint := COALESCE(NEW.order_id, OLD.order_id);
BEGIN
    UPDATE orders
    SET total = (
        SELECT COALESCE(SUM(quantity * unit_price), 0)
        FROM order_items
        WHERE order_id = target_order
    )
    WHERE id = target_order;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER order_items_recalc
    AFTER INSERT OR UPDATE OR DELETE ON order_items
    FOR EACH ROW
    EXECUTE FUNCTION recalc_order_total();""")

    # ───────────────────────────────────────────
    h1(d, "4. Trigger ning xavflari")

    note(d, "Trigger haqidagi asosiy fikrim:",
         "U juda kuchli, lekin **ko'rinmas** vosita. Kodni o'qiyotgan odam "
         "`INSERT` yozilganini ko'radi, lekin uning ortidan yana uchta amal "
         "bajarilishini bilmaydi. Nosozlikni izlayotganda esa bu jiddiy "
         "qiyinchilik tug'diradi — sabab kodda emas, bazada.")

    bullets(d, [
        "**Yashirin xatti-harakat** — ilova kodida ko'rinmaydi.",
        "**Nosozlikni topish qiyin** — stack trace trigger ni ko'rsatmaydi.",
        "**Unumdorlik** — `FOR EACH ROW` ommaviy operatsiyalarda har bir "
        "satr uchun ishlaydi.",
        "**Rekursiya** — trigger o'zi o'zgartirgan jadvalga yana trigger "
        "qo'zg'atishi mumkin.",
        "**Testlash murakkabligi** — trigger ni birlik testida tekshirib "
        "bo'lmaydi.",
    ])

    code(d, """-- Ommaviy yangilashda trigger million marta ishlaydi
UPDATE products SET price = price * 1.1;   -- 1 000 000 satr""")

    para(d, "Bunday holatlarda `FOR EACH STATEMENT` yoki trigger ni vaqtincha "
            "o'chirish qaraladi:")

    code(d, """ALTER TABLE products DISABLE TRIGGER products_log_price;
UPDATE products SET price = price * 1.1;
ALTER TABLE products ENABLE TRIGGER products_log_price;""")

    note(d, "Qachon trigger ishlataman, qachon kodda yozaman:",
         "Agar qoida **har qanday** o'zgarish uchun amal qilishi kerak bo'lsa — "
         "ya'ni ilovam orqali ham, qo'lda SQL orqali ham, boshqa tizim orqali "
         "ham — trigger to'g'ri tanlov. Agar qoida faqat mening ilovam "
         "mantig'iga tegishli bo'lsa — uni kodda yozaman, u yerda ko'rinadi va "
         "testlanadi.")

    # ───────────────────────────────────────────
    h1(d, "5. EF Core bilan ishlashda")

    para(d, "EF Core o'zgartirilgan satrlar sonini hisoblaydi. Agar trigger "
            "qo'shimcha satrlarga ta'sir qilsa, bu hisob buziladi va "
            "`DbUpdateConcurrencyException` otiladi.")

    code(d, """modelBuilder.Entity<Order>()
    .ToTable(tb => tb.HasTrigger("orders_set_updated_at"));""")

    para(d, "Bu sozlama EF Core ga trigger mavjudligini aytadi va u boshqacha "
            "SQL generatsiya qiladi — satrlar sonini `OUTPUT` orqali emas, "
            "alohida so'rov bilan tekshiradi.")

    note(d, "Bu talab SQL Server uchun majburiy:",
         "PostgreSQL da odatda muammo chiqmaydi, lekin SQL Server da "
         "trigger li jadvalga yozishda EF Core xatolik beradi va aynan shu "
         "sozlamani so'raydi. Xatolik xabari ancha tushunarsiz bo'lgani uchun "
         "bu sababni oldindan bilish vaqt tejaydi.")

    # ───────────────────────────────────────────
    h1(d, "6. Ko'rish va boshqarish")

    code(d, """-- Jadvaldagi trigger lar
SELECT tgname, tgenabled
FROM pg_trigger
WHERE tgrelid = 'orders'::regclass AND NOT tgisinternal;

-- Sequence lar va joriy qiymatlari
SELECT schemaname, sequencename, last_value
FROM pg_sequences;

-- Trigger funksiyasining matni
SELECT prosrc FROM pg_proc WHERE proname = 'set_updated_at';""")

    # ───────────────────────────────────────────
    h1(d, "7. Xulosa")

    bullets(d, [
        "Sequence — jadvaldan mustaqil noyob sonlar generatori.",
        "Uning qiymatlari **ketma-ket bo'lishi kafolatlanmaydi** — bekor "
        "qilingan tranzaksiya bo'shliq qoldiradi.",
        "Uzluksiz raqam kerak bo'lsa, alohida hisoblagich jadvali ishlatiladi.",
        "`GENERATED BY DEFAULT AS IDENTITY` — zamonaviy, standartga mos usul.",
        "Trigger hodisaga javoban avtomatik bajariladi: `BEFORE`, `AFTER` yoki "
        "`INSTEAD OF`.",
        "`NEW` va `OLD` satr qiymatlarini beradi; taqqoslashda "
        "`IS DISTINCT FROM` ishlatish kerak.",
        "Trigger ko'rinmas xatti-harakat qo'shadi — nosozlikni topishni "
        "qiyinlashtiradi.",
        "EF Core da trigger li jadval uchun `HasTrigger` ko'rsatilishi kerak.",
    ])

    sources(d, [
        ("CREATE SEQUENCE — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/sql-createsequence.html"),
        ("Triggers — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/triggers.html"),
        ("CREATE TRIGGER — PostgreSQL hujjati",
         "https://www.postgresql.org/docs/current/sql-createtrigger.html"),
        ("Sequences — EF Core",
         "https://learn.microsoft.com/en-us/ef/core/modeling/sequences"),
    ])
